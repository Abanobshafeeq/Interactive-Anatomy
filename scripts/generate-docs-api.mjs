import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import ts from 'typescript';

const root = path.resolve(import.meta.dirname, '..');
const target = path.join(root, 'src/app/features/docs/content');
const relative = file => path.relative(root, file).replaceAll('\\', '/');
const slug = name => name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
function walk(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const file = path.join(directory, entry.name);
    if (entry.isDirectory()) return ['docs', 'testing'].includes(entry.name) ? [] : walk(file);
    return /\.ts$/.test(file) && !/\.spec\.ts$/.test(file) ? [file] : [];
  });
}
const files = walk(path.join(root, 'src/app')).concat(path.join(root, 'src/main.ts')).sort();
const sources = [];
const symbols = [];
const printer = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed });
for (const file of files) {
  const text = fs.readFileSync(file, 'utf8').replaceAll('\r\n', '\n');
  const source = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true);
  const filePath = relative(file);
  const sourceId = filePath.replace(/^src\//, '').replace(/\.ts$/, '').replaceAll('/', '--');
  const dependencies = source.statements.filter(ts.isImportDeclaration).map(node => node.moduleSpecifier.text);
  sources.push({ id: sourceId, path: filePath, text, dependencies,
    hash: crypto.createHash('sha256').update(text).digest('hex').slice(0, 12) });
  for (const node of source.statements) {
    if (!node.modifiers?.some(modifier => modifier.kind === ts.SyntaxKind.ExportKeyword)) continue;
    if (!node.name && !ts.isVariableStatement(node)) continue;
    const declarations = ts.isVariableStatement(node) ? node.declarationList.declarations : [node];
    for (const declaration of declarations) {
      const name = declaration.name?.getText(source);
      if (!name) continue;
      const kind = ts.isClassDeclaration(node) ? 'class' : ts.isInterfaceDeclaration(node) ? 'interface'
        : ts.isTypeAliasDeclaration(node) ? 'type' : ts.isFunctionDeclaration(node) ? 'function' : 'constant';
      const line = source.getLineAndCharacterOfPosition(node.getStart(source)).line + 1;
      const signature = kind === 'class'
        ? `export class ${name}${node.heritageClauses?.map(clause => ` ${clause.getText(source)}`).join('') ?? ''}`
        : ts.isFunctionDeclaration(node) && node.body ? text.slice(node.getStart(source), node.body.getStart(source)).trim()
        : printer.printNode(ts.EmitHint.Unspecified, ts.isVariableStatement(node) ? node : declaration, source);
      const members = kind === 'class' ? node.members.filter(member => member.name || ts.isConstructorDeclaration(member)).map(member => {
        const memberName = ts.isConstructorDeclaration(member) ? 'constructor' : member.name.getText(source);
        const isPrivate = member.modifiers?.some(modifier => modifier.kind === ts.SyntaxKind.PrivateKeyword) ?? false;
        const memberLine = source.getLineAndCharacterOfPosition(member.getStart(source)).line + 1;
        const memberSignature = member.body ? text.slice(member.getStart(source), member.body.getStart(source)).trim()
          : member.getText(source).replace(/;$/, '');
        return { name: memberName, signature: memberSignature, visibility: isPrivate ? 'private' : 'public', line: memberLine };
      }) : [];
      symbols.push({ id: slug(name), name, kind, sourceId, path: filePath, line, signature,
        comment: ts.getJSDocCommentsAndTags(node).map(comment => comment.comment ?? '').filter(value => typeof value === 'string').join('\n'), members });
    }
  }
}
let commit = 'unversioned';
try { commit = execFileSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim(); } catch {}
const outputs = {
  'api.generated.ts': `// Generated by node scripts/generate-docs-api.mjs. Do not edit.\nimport type { ApiSymbol } from '../docs.models';\nexport const API_SYMBOLS: ApiSymbol[] = ${JSON.stringify(symbols, null, 2)};\n`,
  'sources.generated.ts': `// Generated source snapshots; loaded only on source-browser routes.\nimport type { SourceSnapshot } from '../docs.models';\nexport const SOURCE_SNAPSHOTS: SourceSnapshot[] = ${JSON.stringify(sources, null, 2)};\n`,
  'version.generated.ts': `// Source baseline, including working-tree file hashes in the source browser.\nexport const DOCS_VERSION = ${JSON.stringify(commit)};\n`,
};
const examplePath = path.join(root, 'docs/examples/integration.examples.ts');
if (fs.existsSync(examplePath)) {
  const exampleText = fs.readFileSync(examplePath, 'utf8').replaceAll('\r\n', '\n');
  const exampleSource = ts.createSourceFile(examplePath, exampleText, ts.ScriptTarget.Latest, true);
  const imports = exampleSource.statements.filter(ts.isImportDeclaration).map(node => node.getText(exampleSource)).join('\n');
  const examples = Object.fromEntries(exampleSource.statements.filter(node => ts.isFunctionDeclaration(node) || ts.isClassDeclaration(node))
    .map(node => [node.name.text, node.getText(exampleSource)]));
  outputs['examples.generated.ts'] = `// Generated from docs/examples/integration.examples.ts; type-check that file before updating.\nexport const EXAMPLE_IMPORTS = ${JSON.stringify(imports)};\nexport const INTEGRATION_EXAMPLES: Record<string, string> = ${JSON.stringify(examples, null, 2)};\n`;
}
fs.mkdirSync(target, { recursive: true });
for (const [name, content] of Object.entries(outputs)) {
  const file = path.join(target, name);
  if (process.argv.includes('--check')) {
    // The version is an informational generation baseline. Requiring equality to HEAD
    // would make every commit invalidate its own generated metadata indefinitely.
    if (name === 'version.generated.ts') {
      if (!fs.existsSync(file)) { console.error('Missing documentation baseline metadata'); process.exitCode = 1; }
      continue;
    }
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) {
      console.error(`Stale documentation snapshot: ${relative(file)}. Run node scripts/generate-docs-api.mjs`);
      process.exitCode = 1;
    }
  } else fs.writeFileSync(file, content);
}
console.log(`${sources.length} source files, ${symbols.length} exported symbols ${process.argv.includes('--check') ? 'checked' : 'indexed'}.`);
